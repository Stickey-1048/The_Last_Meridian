"""Built records against accepted d142 writing and explicit context projections.

No compiler/native proof. Mapping is a reviewed input, never regenerated by tests.
"""
import json
import re
import subprocess
import unittest
from test_sim import ROOT, PLUGIN, need_build
from test_mercy_briefing_projection import book_texts


class Projection(unittest.TestCase):
    def setUp(self):
        need_build(self)
        self.map = json.loads((ROOT / 'docs/design/NIGHT_MAIL_STORY_001_MAPPING.json').read_text(encoding='utf-8'))
        self.story = ROOT / self.map['source']['folder']
        self.lines = {l['id']:l for f in self.map['source']['files'][:2] for l in json.loads((self.story/f).read_text())['lines']}
        self.docs = {d['id']:d for d in json.loads((self.story/'documents.json').read_text())['documents']}
        self.quest = json.loads((self.story/'quests/tlm_mq02a.json').read_text())
        self.people = {c['id']:c['name'] for c in json.loads((self.story/'characters.json').read_text())['characters']}
        self.plugin = json.loads(PLUGIN.read_text())
        self.messages = {m['EditorId']:m for m in self.plugin['Messages'] if m['EditorId'].startswith('TLM_MSG_NM_')}
        self.road = next(q for q in self.plugin['Quests'] if q['EditorId']=='TLM_MQ02A')

    def test_accepted_input_is_the_accepted_git_text(self):
        for f in self.map['source']['files']:
            name = self.map['source']['folder'] + '/' + f
            old = subprocess.run(['git','show','d142104:'+name],cwd=ROOT,capture_output=True,check=True).stdout.decode('utf-8')
            self.assertEqual((ROOT/name).read_text(encoding='utf-8'), old.replace('\r\n','\n'), name)

    def test_every_message_has_exactly_one_mapping(self):
        names = [e['record'] for e in self.map['speech']+self.map['ui']]
        names += [p for d in self.map['documents'] for p in d['pages']]
        self.assertEqual(len(names),len(set(names)))
        self.assertEqual(set(names),set(self.messages))
        self.assertEqual((len(self.map['speech']),len(self.map['ui']),len(self.map['documents'])),(29,88,3))

    def test_spoken_text_is_accepted_text_with_only_three_declared_excerpts(self):
        exceptions = {}
        for e in self.map['speech']:
            text = self.lines[e['node']]['text']; part=e['part']
            self.assertEqual(e['speaker'],self.people[self.lines[e['node']]['speaker']])
            if part!='whole':
                method,at=part.split(':',1)
                self.assertEqual(text.count(at),1)
                exceptions[e['record']]=part
                text = text.split(at)[0] if method=='before' else (at+text.split(at)[1] if method=='from' else (at+text.split(at)[1]).lstrip())
            m=self.messages[e['record']]
            self.assertEqual(m['Title'],e['speaker'])
            self.assertEqual(m['Text'],e['speaker']+': "'+text+'"',e['record'])
            self.assertNotIn('[',m['Text'])
        self.assertEqual(set(exceptions),{'TLM_MSG_NM_LockridgeGateA','TLM_MSG_NM_LockridgeGateB','TLM_MSG_NM_DoleShareNoBillie'})
        a=self.messages['TLM_MSG_NM_LockridgeGateA']['Text'].split(': "',1)[1][:-1]
        b=self.messages['TLM_MSG_NM_LockridgeGateB']['Text'].split(': "',1)[1][:-1]
        self.assertEqual(a+' '+b,self.lines['lockridge_gate']['text'])

    def test_buttons_preserve_labels_and_declare_exact_five_projections(self):
        projections={}
        for e in self.map['speech']:
            actual=[b['Text'] for b in self.messages[e['record']]['Buttons']]
            self.assertEqual(actual,e['buttons'])
            source=[b['label'] for b in self.lines[e['node']].get('buttons',[])] or ['Continue']
            if e['button_mode']=='node':self.assertEqual(actual,source)
            else:projections[e['record']]=actual
        self.assertEqual(projections,{
            'TLM_MSG_NM_LockridgeGateA':['Continue'],
            'TLM_MSG_NM_LockridgeStamp':self.map_button_source('lockridge_stamp')+['(Close the drawer)'],
            'TLM_MSG_NM_DoleShareNoBillie':['Continue'],
            'TLM_MSG_NM_ReportKnown':['[Report on Iron Junction]','[Later]'],
            'TLM_MSG_NM_ReportUnknown':['[Report on Iron Junction]','[Later]'],
        })

    def map_button_source(self,node):
        return [b['label'] for b in self.lines[node]['buttons']]

    def test_own_ui_is_bracketed_pinned_and_never_spoken(self):
        for e in self.map['ui']:
            m=self.messages[e['record']]
            self.assertIsNone(m['Title'])
            self.assertTrue(m['Text'].startswith('['))
            self.assertEqual(m['Text'],e['text'])
            self.assertEqual([b['Text'] for b in m['Buttons']],e['buttons'])

    def test_documents_are_whole_and_book_is_actual_binary_text(self):
        for d in self.map['documents']:
            doc=self.docs[d['document']]; at=0
            for n,name in enumerate(d['pages'],1):
                m=self.messages[name]; heading='[%s, page %d of %d]\n\n'%(doc['title'],n,len(d['pages']))
                self.assertTrue(m['Text'].startswith(heading))
                page=m['Text'][len(heading):]
                self.assertTrue(doc['text'].startswith(page,at))
                at+=len(page)
                while at<len(doc['text']) and doc['text'][at]=='\n':at+=1
                self.assertEqual([b['Text'] for b in m['Buttons']],['Continue'])
            self.assertEqual(at,len(doc['text']))
        # The portable runner copies JSON into build/sim, not the binary.
        # The skeleton build contains the same authored BOOK records.
        books=book_texts(ROOT/'build/TheLastMeridian.esp')
        doc=next(d for d in self.docs.values() if d['title']=='Flyleaf of a Hymnal')
        self.assertEqual(books['TLM_BOOK_HymnalFlyleaf'],(doc['title'],doc['text']))

    def test_all_journals_and_objectives_are_accepted_or_exact_neutral_projection(self):
        source={s['n']:s['log'] for s in self.quest['stages']}
        self.assertEqual([s['Index'] for s in self.road['Stages']],[s['stage'] for s in self.map['journal']])
        for built,e in zip(self.road['Stages'],self.map['journal']):
            self.assertEqual((built['Log'],built['Note'],built['CompleteQuest']),(e['text'],e['context'],e['completes']))
            if e['kind']=='accepted':self.assertEqual(e['text'],source[e['stage']])
        self.assertEqual({e['stage'] for e in self.map['journal'] if e['kind']=='projection'}, {21,31,46,47,48,49,51,56,62,64})
        self.assertEqual([s['Index'] for s in self.road['Stages'] if s['CompleteQuest']],[100])
        accepted_objectives={o['n']:o['text'] for o in self.quest['objectives']}
        for built,e in zip(self.road['Objectives'],self.map['objectives']):
            self.assertEqual((built['Index'],built['Text']),(e['index'],e['text']))
            if e['kind']=='accepted':self.assertEqual(e['text'],accepted_objectives[e['index']])
        self.assertEqual(len(self.road['Objectives']),len(self.map['objectives']))

    def test_alias_identity_is_pinned_without_master_id_drift(self):
        for name,want in self.map['aliases'].items():
            q=next(q for q in self.plugin['Quests'] if q['EditorId']==name)
            self.assertEqual(q['Aliases'],want)

    def test_own_cell_contains_all_forty_nine_interior_aliases_and_forty_five_floor_tiles(self):
        cells=[c for c in self.plugin['Cells'] if c['OfThisPlugin']]
        self.assertEqual([c['EditorId'] for c in cells],['TLM_CELL_NightMail'])
        placed={p['EditorId']:p for p in cells[0]['Placed']}
        expected={'TLM_REF_NM_'+a['Name'] for a in self.map['aliases']['TLM_NM'] if a['Name'] not in ('MercyTravel','MercyReturn')}
        floors={n for n in placed if '_Floor_' in n}
        self.assertEqual((len(expected),len(floors)),(49,45))
        self.assertEqual(set(placed),expected|floors)
        for name in floors:
            self.assertFalse(placed[name]['InitiallyDisabled'])
            self.assertEqual(placed[name]['Position'][2],0)

    def test_strings_are_short_and_no_extra_button_conditions_exist(self):
        for name,m in self.messages.items():
            self.assertLessEqual(len(m['Text']),240,name)
            self.assertLessEqual(len(m['Buttons']),4,name)
            self.assertTrue(m['Box'],name)
            for b in m['Buttons']:
                self.assertFalse(b['Conditions'],name)
                self.assertLessEqual(len(b['Text']),240,name)


if __name__=='__main__':unittest.main()
